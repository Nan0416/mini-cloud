#!/usr/bin/env node
/**
 * Compiles `packages/service/migrations/*.sql` into a module the binary bundle uses in
 * place of `src/data/embedded-migrations.ts`.
 *
 * A single executable has no files beside it, so the schema has to travel inside it.
 * Generated at build time rather than checked in, because a checked-in copy is a
 * second source of truth that goes stale the first time someone adds a migration and
 * forgets to regenerate — and the failure would be a binary that silently applies an
 * older schema than the repository describes.
 */
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const cliDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const migrationsDir = resolve(cliDir, '..', 'service', 'migrations');
const outFile = join(cliDir, 'build', 'generated', 'embedded-migrations.ts');

const files = readdirSync(migrationsDir, { withFileTypes: true })
  .filter((entry) => entry.isFile() && entry.name.endsWith('.sql'))
  .map((entry) => entry.name)
  .sort();

if (files.length === 0) {
  throw new Error(`No .sql files in ${migrationsDir}. A binary built now would start and then fail to create its own schema.`);
}

// Ordering and validation are deliberately NOT done here: `orderMigrations` in the
// service owns those rules, and a second implementation would be a second thing to
// keep in step. This only has to produce the name/SQL pairs.
const entries = files.map((file) => `  ${JSON.stringify(file)}: ${JSON.stringify(readFileSync(join(migrationsDir, file), 'utf-8'))},`).join('\n');

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(
  outFile,
  `// Generated by scripts/generate-embedded-migrations.mjs. Do not edit.
// ${files.length} migration(s) compiled in from packages/service/migrations.
export const EMBEDDED_MIGRATIONS: Readonly<Record<string, string>> = {
${entries}
};
`,
  'utf-8',
);

console.log(`Compiled ${files.length} migration(s) into ${outFile}: ${files.join(', ')}`);

// The version too: a binary has no package.json beside it, so the value CI stamped has
// to be compiled in or every release reports whatever was hard-coded.
const version = JSON.parse(readFileSync(join(cliDir, 'package.json'), 'utf-8')).version;
const versionFile = join(cliDir, 'build', 'generated', 'version.ts');
writeFileSync(versionFile, `// Generated by scripts/generate-embedded-migrations.mjs. Do not edit.\nexport function cliVersion(): string {\n  return ${JSON.stringify(version)};\n}\n`, 'utf-8');
console.log(`Compiled version ${version} into ${versionFile}`);
